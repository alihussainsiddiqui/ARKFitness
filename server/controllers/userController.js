const User = require('../models/User');

// @desc    Update user profile
// @route   PUT /api/users/profile
const updateUserProfile = async (req, res) => {
  try {
    const user = await User.findById(req.user.id);

    if (user) {
      user.username = req.body.username || user.username;
      user.email = req.body.email || user.email;
      
      if (req.body.password) {
        user.password = req.body.password;
      }

      // NEW: Catch and save the global macro goals
      if (req.body.macroGoals) {
        user.macroGoals = {
          calories: req.body.macroGoals.calories || user.macroGoals?.calories,
          protein: req.body.macroGoals.protein || user.macroGoals?.protein,
          carbs: req.body.macroGoals.carbs || user.macroGoals?.carbs,
          fat: req.body.macroGoals.fat || user.macroGoals?.fat
        };
      }

      const updatedUser = await user.save();

      // Return the updated user along with the existing token
      res.json({
        _id: updatedUser._id,
        username: updatedUser.username,
        email: updatedUser.email,
        avatar: updatedUser.avatar, 
        macroGoals: updatedUser.macroGoals, // Added this so frontend auth state knows the goals
        token: req.headers.authorization.split(' ')[1] 
      });
    } else {
      res.status(404).json({ message: 'User not found' });
    }
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};

// @desc    Upload user avatar to Cloudinary
// @route   POST /api/users/avatar
const uploadAvatar = async (req, res) => {
  try {
    if (!req.file) {
      return res.status(400).json({ message: 'No image file provided' });
    }

    // req.file.path is the secure URL automatically generated by Cloudinary
    const avatarUrl = req.file.path; 

    const user = await User.findById(req.user.id);
    if (!user) {
      return res.status(404).json({ message: 'User not found' });
    }
    
    user.avatar = avatarUrl;
    const updatedUser = await user.save();

    res.status(200).json({ 
      message: 'Avatar updated successfully', 
      avatar: updatedUser.avatar,
      _id: updatedUser._id,
      username: updatedUser.username,
      email: updatedUser.email,
      macroGoals: updatedUser.macroGoals, // Keeping global state payload consistent
      token: req.headers.authorization.split(' ')[1] 
    });
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};
// @desc    Search for users (Community)
// @route   GET /api/users?search=name
const searchUsers = async (req, res) => {
  try {
    const keyword = req.query.search
      ? { username: { $regex: req.query.search, $options: 'i' } }
      : {}; 

    // FIX: Added macroGoals and createdAt so the frontend popup is actually interesting
    const users = await User.find({ ...keyword, _id: { $ne: req.user.id } })
      .select('_id username avatar macroGoals createdAt')
      .limit(50); 

    res.json(users);
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};
module.exports = { updateUserProfile, uploadAvatar, searchUsers };